    env["MRG_TREE_BETA_MRG"] = str(TREE_BETA_MRG)
    env["MRG_TREE_ETA_HISTORY"] = str(TREE_ETA_HISTORY)
    env["MRG_TREE_GAMMA_DEP"] = str(TREE_GAMMA_DEP)
    env["MRG_TREE_RHO_REDUNDANCY"] = str(TREE_RHO_REDUNDANCY)
