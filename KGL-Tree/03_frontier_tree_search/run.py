    env["MRG_SC_DEVICE"] = DEVICE
    env["MRG_SC_EMBEDDING_URL"] = EMBEDDING_URL
    env["MRG_SC_EMBEDDING_MODEL"] = EMBEDDING_MODEL
    env["MRG_SC_EMBEDDING_TIMEOUT"] = EMBEDDING_TIMEOUT
    env["MRG_TREE_KG_PATH"] = str(TRAIN_DB_DIR / KG_FILENAME)
    env["MRG_TREE_MODEL_PATH"] = str(TRAIN_DB_DIR / MODEL_FILENAME)
    env["MRG_TREE_TRAIN_TASKS_FILE"] = str(TRAIN_DB_DIR / TRAIN_TASKS_FILENAME)
    env["MRG_TREE_SERVICE_FILE"] = str(TEST_DB_DIR / SERVICE_FILENAME)
    env["MRG_TREE_USE_BEAM"] = str(USE_BEAM)
    env["MRG_TREE_BEAM_WIDTH"] = str(BEAM_WIDTH)
    env["MRG_TREE_USE_DYNAMIC_BEAM"] = str(USE_DYNAMIC_BEAM)
    env["MRG_TREE_BEAM_MIN"] = str(BEAM_MIN)
    env["MRG_TREE_BEAM_MAX"] = str(BEAM_MAX)
    env["MRG_TREE_BEAM_THRESHOLD_HIGH"] = str(BEAM_THRESHOLD_HIGH)
    env["MRG_TREE_BEAM_THRESHOLD_LOW"] = str(BEAM_THRESHOLD_LOW)
