    env["MRG_TREE_HISTORY_BONUS_LATER"] = str(HISTORY_BONUS_LATER)
    env["MRG_TREE_STRICT_NEIGHBOR_ONLY_AFTER_STEP1"] = str(STRICT_NEIGHBOR_ONLY_AFTER_STEP1)
    env["MRG_TREE_REQUIREMENT_TOPK"] = str(REQUIREMENT_TOPK)
    env["MRG_TREE_REQUIREMENT_MIN_PLAN_SIZE"] = str(REQUIREMENT_MIN_PLAN_SIZE)
    env["MRG_TREE_REQUIREMENT_COVERAGE_THRESHOLD"] = str(REQUIREMENT_COVERAGE_THRESHOLD)
    env["MRG_TREE_BUDGET_MULTIPLIER"] = str(TREE_BUDGET_MULTIPLIER)
    env["MRG_TREE_QUEUE_SIZE"] = str(TREE_QUEUE_SIZE)
    env["MRG_TREE_CHILDREN_PER_REQUIREMENT"] = str(TREE_CHILDREN_PER_REQUIREMENT)
    env["MRG_TREE_RELATION_KEEP"] = str(TREE_RELATION_KEEP)
    env["MRG_TREE_MATCH_THRESHOLD"] = str(TREE_MATCH_THRESHOLD)
    env["MRG_TREE_MRG_PROB_THRESHOLD"] = str(TREE_MRG_PROB_THRESHOLD)
