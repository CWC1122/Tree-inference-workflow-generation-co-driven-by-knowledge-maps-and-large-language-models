def main() -> None:
    if not SCRIPT_PATH.exists():
        raise FileNotFoundError(f"Script not found: {SCRIPT_PATH}")

    env = build_env()
    print("=== MODULE 3: FRONTIER TREE SEARCH ===")
    print(f"PROJECT_ROOT     = {PROJECT_ROOT}")
    print(f"DATA_FOLDER_NAME = {DATA_FOLDER_NAME}")
    print(f"DATABASE_NAME    = {DATABASE_NAME}")
    print(f"TEST_DB_DIR      = {TEST_DB_DIR}")
    print(f"TRAIN_DB_DIR     = {TRAIN_DB_DIR}")
    print(f"INPUT_FILE       = {INPUT_FILE}")
    print(f"OUTPUT_FILE      = {OUTPUT_FILE}")
    print(f"UNFINISHED_FILE  = {UNFINISHED_FILE}")
    print(f"MAX_WORKERS      = {MAX_WORKERS}")
    print(f"SAVE_INTERVAL    = {SAVE_INTERVAL}")
    print(f"TASK_TIMEOUT     = {TASK_TIMEOUT}")
    print(f"DEVICE           = {DEVICE}")
    print(f"EMBEDDING_URL    = {EMBEDDING_URL}")
    print(f"EMBEDDING_MODEL  = {EMBEDDING_MODEL}")

    subprocess.run(
        [sys.executable, str(SCRIPT_PATH)],
        cwd=str(MODULE_ROOT),
        env=env,
        check=True,
    )


if __name__ == "__main__":
    main()
